/* Pedido de Venda — schema Firebird 3+/5
   Tabelas: CLIENTE, PRODUTO, PEDIDO, PEDIDO_ITEM
   NUMERO_PEDIDO: sequence GEN_PEDIDO_NUMERO (+ trigger de fallback)
   PEDIDO_ITEM.ID: GENERATED BY DEFAULT AS IDENTITY

   Uso (banco ja existente):
     isql -user SYSDBA -password firebird -i database/db.sql caminho/DEVHUNTER.FDB
*/

SET SQL DIALECT 3;

/* Remove objetos anteriores sem abortar na 1a execucao. */
SET TERM ^ ;
EXECUTE BLOCK AS
BEGIN
  BEGIN
    EXECUTE STATEMENT 'DROP TABLE PEDIDO_ITEM';
  WHEN ANY DO BEGIN END
  END
  BEGIN
    EXECUTE STATEMENT 'DROP TABLE PEDIDO';
  WHEN ANY DO BEGIN END
  END
  BEGIN
    EXECUTE STATEMENT 'DROP TABLE PRODUTO';
  WHEN ANY DO BEGIN END
  END
  BEGIN
    EXECUTE STATEMENT 'DROP TABLE CLIENTE';
  WHEN ANY DO BEGIN END
  END
  BEGIN
    EXECUTE STATEMENT 'DROP SEQUENCE GEN_PEDIDO_NUMERO';
  WHEN ANY DO BEGIN END
  END
END^
SET TERM ; ^
COMMIT;

CREATE TABLE CLIENTE (
  CODIGO INTEGER NOT NULL,
  NOME   VARCHAR(80) NOT NULL,
  CIDADE VARCHAR(60) NOT NULL,
  UF     CHAR(2) NOT NULL,
  CONSTRAINT PK_CLIENTE PRIMARY KEY (CODIGO)
);

CREATE TABLE PRODUTO (
  CODIGO      INTEGER NOT NULL,
  DESCRICAO   VARCHAR(80) NOT NULL,
  PRECO_VENDA NUMERIC(15,2) NOT NULL,
  CONSTRAINT PK_PRODUTO PRIMARY KEY (CODIGO),
  CONSTRAINT CK_PRODUTO_PRECO CHECK (PRECO_VENDA >= 0)
);

CREATE SEQUENCE GEN_PEDIDO_NUMERO;
ALTER SEQUENCE GEN_PEDIDO_NUMERO RESTART WITH 1;

CREATE TABLE PEDIDO (
  NUMERO_PEDIDO  INTEGER NOT NULL,
  DATA_EMISSAO   DATE DEFAULT CURRENT_DATE NOT NULL,
  CODIGO_CLIENTE INTEGER NOT NULL,
  VALOR_TOTAL    NUMERIC(15,2) DEFAULT 0 NOT NULL,
  OBSERVACAO     VARCHAR(80),
  CONSTRAINT PK_PEDIDO PRIMARY KEY (NUMERO_PEDIDO),
  CONSTRAINT FK_PEDIDO_CLIENTE
    FOREIGN KEY (CODIGO_CLIENTE) REFERENCES CLIENTE (CODIGO),
  CONSTRAINT CK_PEDIDO_TOTAL CHECK (VALOR_TOTAL >= 0)
);

CREATE TABLE PEDIDO_ITEM (
  ID             INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  NUMERO_PEDIDO  INTEGER NOT NULL,
  CODIGO_PRODUTO INTEGER NOT NULL,
  QUANTIDADE     NUMERIC(15,3) NOT NULL,
  VLR_UNITARIO   NUMERIC(15,2) NOT NULL,
  VLR_TOTAL      NUMERIC(15,2) NOT NULL,
  CONSTRAINT PK_PEDIDO_ITEM PRIMARY KEY (ID),
  CONSTRAINT FK_ITEM_PEDIDO
    FOREIGN KEY (NUMERO_PEDIDO) REFERENCES PEDIDO (NUMERO_PEDIDO) ON DELETE CASCADE,
  CONSTRAINT FK_ITEM_PRODUTO
    FOREIGN KEY (CODIGO_PRODUTO) REFERENCES PRODUTO (CODIGO),
  CONSTRAINT CK_ITEM_QTD CHECK (QUANTIDADE > 0),
  CONSTRAINT CK_ITEM_VLR CHECK (VLR_UNITARIO >= 0),
  CONSTRAINT CK_ITEM_TOTAL CHECK (VLR_TOTAL >= 0)
);

CREATE INDEX IX_PEDIDO_CLIENTE ON PEDIDO (CODIGO_CLIENTE);
CREATE INDEX IX_ITEM_PEDIDO ON PEDIDO_ITEM (NUMERO_PEDIDO);
CREATE INDEX IX_ITEM_PRODUTO ON PEDIDO_ITEM (CODIGO_PRODUTO);

SET TERM ^ ;
CREATE OR ALTER TRIGGER TRG_PEDIDO_BI FOR PEDIDO
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
  /* A app ja reserva o numero via NEXT VALUE; o trigger cobre INSERT sem numero. */
  IF (NEW.NUMERO_PEDIDO IS NULL OR NEW.NUMERO_PEDIDO = 0) THEN
    NEW.NUMERO_PEDIDO = NEXT VALUE FOR GEN_PEDIDO_NUMERO;
END^
SET TERM ; ^

